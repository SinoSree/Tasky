#!/bin/sh
# ---------------------------------------------------------------------------
# build-standalone.sh
#
# Packs everything in src/ into ONE self-contained file: index.html
#
# Why this exists: a normal React project needs Node.js to run `npm run dev`.
# This script needs only `sed` and `cat`, which every Mac already has, so the
# app can be opened and used immediately.
#
# It does the same job a bundler does, but very simply:
#   1. read each source file in dependency order
#   2. delete the `import` lines and the `export` keywords
#      (those are only needed while the files are separate modules)
#   3. glue the result into one <script type="text/babel"> block
#   4. inline styles.css so the file really is standalone
#
# Babel (loaded from a CDN) then compiles the JSX inside the browser.
#
# Run it with:   sh build-standalone.sh
# ---------------------------------------------------------------------------
set -eu
cd "$(dirname "$0")"

OUT=index.html

# Order matters: a file must come after anything it relies on at load time.
FILES="
src/lib/constants.js
src/lib/storage.js
src/lib/taskUtils.js
src/lib/supabaseConfig.js
src/lib/supabaseClient.js
src/lib/repo.js
src/context/AuthContext.jsx
src/context/TaskContext.jsx
src/components/Icon.jsx
src/components/Avatar.jsx
src/components/Button.jsx
src/components/Badge.jsx
src/components/Modal.jsx
src/components/ConfirmDialog.jsx
src/components/EmptyState.jsx
src/components/TaskForm.jsx
src/components/TaskCard.jsx
src/components/TaskRow.jsx
src/components/StatCard.jsx
src/components/FilterBar.jsx
src/components/UserMenu.jsx
src/components/LoginScreen.jsx
src/components/Sidebar.jsx
src/components/Topbar.jsx
src/pages/Dashboard.jsx
src/pages/TaskList.jsx
src/pages/KanbanBoard.jsx
src/pages/CalendarView.jsx
src/pages/Categories.jsx
src/pages/Team.jsx
src/App.jsx
"

# --- head of the HTML file -------------------------------------------------
cat > "$OUT" <<'HEAD'
<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<title>Taskly — Task Manager</title>
<link rel="preconnect" href="https://fonts.googleapis.com" />
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet" />
<style>
HEAD

cat src/styles.css >> "$OUT"

cat >> "$OUT" <<'MID'
</style>
</head>
<body>
<div id="root"></div>

<script src="https://unpkg.com/react@18.3.1/umd/react.production.min.js" crossorigin></script>
<script src="https://unpkg.com/react-dom@18.3.1/umd/react-dom.production.min.js" crossorigin></script>
<script src="https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.47.10/dist/umd/supabase.min.js" crossorigin></script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/babel-standalone/7.26.4/babel.min.js" crossorigin></script>

<script type="text/babel" data-presets="react">
// Generated by build-standalone.sh — edit the files in src/, never this file.
const { useState, useEffect, useRef, useMemo, useCallback, createContext, useContext } = React;
const { createRoot } = ReactDOM;
MID

# --- every source file, with module syntax removed -------------------------
count=0
for f in $FILES; do
  printf '\n/* ===== %s ===== */\n' "$f" >> "$OUT"
  sed -E \
    -e '/^[[:space:]]*import[[:space:]].*;[[:space:]]*$/d' \
    -e 's/^export default //' \
    -e 's/^export (function|const|class) /\1 /' \
    "$f" >> "$OUT"
  count=$((count + 1))
done

# --- tail: mount the app ---------------------------------------------------
cat >> "$OUT" <<'TAIL'

/* ===== mount the app ===== */
createRoot(document.getElementById('root')).render(<App />);
</script>
</body>
</html>
TAIL

echo "Built $OUT from $count source files ($(wc -c < "$OUT" | tr -d ' ') bytes)"
